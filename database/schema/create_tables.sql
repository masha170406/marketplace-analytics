-- This script creates the 12 project tables and inserts the lookup values for listing, order and payment statuses.

CREATE TABLE USERS (
	USER_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	EMAIL VARCHAR(255) NOT NULL UNIQUE,
	USERNAME VARCHAR(50) NOT NULL UNIQUE,
	FIRST_NAME VARCHAR(100),
	LAST_NAME VARCHAR(100),
	COUNTRY VARCHAR(100) NOT NULL,
	CITY VARCHAR(100),
	REGISTRATION_DATE TIMESTAMPTZ NOT NULL,
	ACCOUNT_STATUS VARCHAR(20) NOT NULL DEFAULT 'active',
	CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CONSTRAINT CHK_USER_ACCOUNT_STATUS CHECK (
		ACCOUNT_STATUS IN ('active', 'suspended', 'deleted')
	)
);

CREATE TABLE CATEGORIES (
	CATEGORY_ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	CATEGORY_NAME VARCHAR(100) NOT NULL,
	PARENT_CATEGORY_ID INTEGER,
	DESCRIPTION TEXT,
	IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
	CONSTRAINT FK_CATEGORY_PARENT FOREIGN KEY (PARENT_CATEGORY_ID) REFERENCES CATEGORIES (CATEGORY_ID),
	CONSTRAINT CHK_CATEGORY_NOT_SELF_PARENT CHECK (
		PARENT_CATEGORY_ID IS NULL
		OR PARENT_CATEGORY_ID <> CATEGORY_ID
	),
	CONSTRAINT UQ_CATEGORY_PARENT_NAME UNIQUE (PARENT_CATEGORY_ID, CATEGORY_NAME)
);

CREATE TABLE LISTING_STATUSES (
	LISTING_STATUS_ID SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	STATUS_NAME VARCHAR(30) NOT NULL UNIQUE,
	DESCRIPTION TEXT
);

CREATE TABLE LISTINGS (
	LISTING_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	SELLER_ID BIGINT NOT NULL,
	CATEGORY_ID INTEGER NOT NULL,
	LISTING_STATUS_ID SMALLINT NOT NULL,
	TITLE VARCHAR(255) NOT NULL,
	DESCRIPTION TEXT,
	CONDITION VARCHAR(30) NOT NULL,
	PRICE NUMERIC(10, 2) NOT NULL,
	CURRENCY CHAR(3) NOT NULL DEFAULT 'EUR',
	CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	PUBLISHED_AT TIMESTAMPTZ,
	EXPIRES_AT TIMESTAMPTZ,
	CONSTRAINT FK_LISTING_SELLER FOREIGN KEY (SELLER_ID) REFERENCES USERS (USER_ID),
	CONSTRAINT FK_LISTING_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES (CATEGORY_ID),
	CONSTRAINT FK_LISTING_STATUS FOREIGN KEY (LISTING_STATUS_ID) REFERENCES LISTING_STATUSES (LISTING_STATUS_ID),
	CONSTRAINT CHK_LISTING_PRICE CHECK (PRICE > 0),
	CONSTRAINT CHK_LISTING_CONDITION CHECK (
		CONDITION IN (
			'new_with_tags',
			'new_without_tags',
			'very_good',
			'good',
			'satisfactory'
		)
	),
	CONSTRAINT CHK_LISTING_EXPIRATION CHECK (
		EXPIRES_AT IS NULL
		OR EXPIRES_AT > CREATED_AT
	),
	CONSTRAINT CHK_LISTING_PUBLICATION CHECK (
		PUBLISHED_AT IS NULL
		OR PUBLISHED_AT >= CREATED_AT
	)
);

CREATE TABLE LISTING_STATUS_HISTORY (
	HISTORY_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	LISTING_ID BIGINT NOT NULL,
	LISTING_STATUS_ID SMALLINT NOT NULL,
	CHANGED_BY_USER_ID BIGINT,
	CHANGED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CHANGE_REASON TEXT,
	CONSTRAINT FK_LISTING_HISTORY_LISTING FOREIGN KEY (LISTING_ID) REFERENCES LISTINGS (LISTING_ID),
	CONSTRAINT FK_LISTING_HISTORY_STATUS FOREIGN KEY (LISTING_STATUS_ID) REFERENCES LISTING_STATUSES (LISTING_STATUS_ID),
	CONSTRAINT FK_LISTING_HISTORY_USER FOREIGN KEY (CHANGED_BY_USER_ID) REFERENCES USERS (USER_ID)
);

CREATE TABLE ORDER_STATUSES (
	ORDER_STATUS_ID SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	STATUS_NAME VARCHAR(30) NOT NULL UNIQUE,
	DESCRIPTION TEXT
);

CREATE TABLE ORDERS (
	ORDER_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	BUYER_ID BIGINT NOT NULL,
	SELLER_ID BIGINT NOT NULL,
	ORDER_STATUS_ID SMALLINT NOT NULL,
	ITEM_SUBTOTAL NUMERIC(12, 2) NOT NULL,
	BUYER_FEE NUMERIC(12, 2) NOT NULL DEFAULT 0,
	SELLER_FEE NUMERIC(12, 2) NOT NULL DEFAULT 0,
	SHIPPING_FEE NUMERIC(12, 2) NOT NULL DEFAULT 0,
	TOTAL_AMOUNT NUMERIC(12, 2) NOT NULL,
	CURRENCY CHAR(3) NOT NULL DEFAULT 'EUR',
	CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	COMPLETED_AT TIMESTAMPTZ,
	CANCELLED_AT TIMESTAMPTZ,
	CONSTRAINT FK_ORDER_BUYER FOREIGN KEY (BUYER_ID) REFERENCES USERS (USER_ID),
	CONSTRAINT FK_ORDER_SELLER FOREIGN KEY (SELLER_ID) REFERENCES USERS (USER_ID),
	CONSTRAINT FK_ORDER_STATUS FOREIGN KEY (ORDER_STATUS_ID) REFERENCES ORDER_STATUSES (ORDER_STATUS_ID),
	CONSTRAINT CHK_ORDER_DIFFERENT_USERS CHECK (BUYER_ID <> SELLER_ID),
	CONSTRAINT CHK_ORDER_SUBTOTAL CHECK (ITEM_SUBTOTAL >= 0),
	CONSTRAINT CHK_ORDER_FEES CHECK (
		BUYER_FEE >= 0
		AND SELLER_FEE >= 0
		AND SHIPPING_FEE >= 0
	),
	CONSTRAINT CHK_ORDER_TOTAL CHECK (
		TOTAL_AMOUNT = ITEM_SUBTOTAL + BUYER_FEE + SHIPPING_FEE
	),
	CONSTRAINT CHK_ORDER_DATES CHECK (
		(
			COMPLETED_AT IS NULL
			OR COMPLETED_AT >= CREATED_AT
		)
		AND (
			CANCELLED_AT IS NULL
			OR CANCELLED_AT >= CREATED_AT
		)
	),
	CONSTRAINT CHK_ORDER_TERMINAL_DATES CHECK (
		NOT (
			COMPLETED_AT IS NOT NULL
			AND CANCELLED_AT IS NOT NULL
		)
	)
);

CREATE TABLE ORDER_ITEMS (
	ORDER_ITEM_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	ORDER_ID BIGINT NOT NULL,
	LISTING_ID BIGINT NOT NULL UNIQUE,
	ITEM_PRICE NUMERIC(10, 2) NOT NULL,
	CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CONSTRAINT FK_ORDER_ITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
	CONSTRAINT FK_ORDER_ITEM_LISTING FOREIGN KEY (LISTING_ID) REFERENCES LISTINGS (LISTING_ID),
	CONSTRAINT CHK_ORDER_ITEM_PRICE CHECK (ITEM_PRICE > 0)
);

CREATE TABLE ORDER_STATUS_HISTORY (
	HISTORY_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	ORDER_ID BIGINT NOT NULL,
	ORDER_STATUS_ID SMALLINT NOT NULL,
	CHANGED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CHANGE_REASON TEXT,
	CONSTRAINT FK_ORDER_HISTORY_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
	CONSTRAINT FK_ORDER_HISTORY_STATUS FOREIGN KEY (ORDER_STATUS_ID) REFERENCES ORDER_STATUSES (ORDER_STATUS_ID)
);

CREATE TABLE PAYMENT_STATUSES (
	PAYMENT_STATUS_ID SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	STATUS_NAME VARCHAR(30) NOT NULL UNIQUE,
	DESCRIPTION TEXT
);

CREATE TABLE PAYMENTS (
	PAYMENT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	ORDER_ID BIGINT NOT NULL,
	PAYMENT_STATUS_ID SMALLINT NOT NULL,
	PAYMENT_METHOD VARCHAR(30) NOT NULL,
	AMOUNT NUMERIC(12, 2) NOT NULL,
	CURRENCY CHAR(3) NOT NULL DEFAULT 'EUR',
	PROVIDER_REFERENCE VARCHAR(255) UNIQUE,
	CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	PAID_AT TIMESTAMPTZ,
	CONSTRAINT FK_PAYMENT_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
	CONSTRAINT FK_PAYMENT_STATUS FOREIGN KEY (PAYMENT_STATUS_ID) REFERENCES PAYMENT_STATUSES (PAYMENT_STATUS_ID),
	CONSTRAINT CHK_PAYMENT_AMOUNT CHECK (AMOUNT > 0),
	CONSTRAINT CHK_PAYMENT_METHOD CHECK (
		PAYMENT_METHOD IN (
			'card',
			'paypal',
			'bank_transfer',
			'apple_pay',
			'google_pay'
		)
	),
	CONSTRAINT CHK_PAYMENT_DATE CHECK (
		PAID_AT IS NULL
		OR PAID_AT >= CREATED_AT
	)
);

CREATE TABLE REVIEWS (
	REVIEW_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	ORDER_ID BIGINT NOT NULL,
	REVIEWER_ID BIGINT NOT NULL,
	REVIEWEE_ID BIGINT NOT NULL,
	RATING SMALLINT NOT NULL,
	COMMENT TEXT,
	CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CONSTRAINT FK_REVIEW_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
	CONSTRAINT FK_REVIEW_REVIEWER FOREIGN KEY (REVIEWER_ID) REFERENCES USERS (USER_ID),
	CONSTRAINT FK_REVIEW_REVIEWEE FOREIGN KEY (REVIEWEE_ID) REFERENCES USERS (USER_ID),
	CONSTRAINT CHK_REVIEW_RATING CHECK (RATING BETWEEN 1 AND 5),
	CONSTRAINT CHK_REVIEW_DIFFERENT_USERS CHECK (REVIEWER_ID <> REVIEWEE_ID),
	CONSTRAINT UQ_REVIEW_PER_ORDER UNIQUE (ORDER_ID, REVIEWER_ID)
);

-- INDEXES
-- Categories: prevent duplicate top-level category names.
-- The composite UNIQUE constraint handles categories with a parent.
CREATE UNIQUE INDEX UQ_CATEGORIES_ROOT_NAME ON CATEGORIES (CATEGORY_NAME)
WHERE
	PARENT_CATEGORY_ID IS NULL;

--
-- Users
CREATE INDEX IDX_USERS_REGISTRATION_DATE ON USERS (REGISTRATION_DATE);

CREATE INDEX IDX_USERS_COUNTRY ON USERS (COUNTRY);

-- Listings
CREATE INDEX IDX_LISTINGS_SELLER ON LISTINGS (SELLER_ID);

CREATE INDEX IDX_LISTINGS_CATEGORY ON LISTINGS (CATEGORY_ID);

CREATE INDEX IDX_LISTINGS_STATUS ON LISTINGS (LISTING_STATUS_ID);

CREATE INDEX IDX_LISTINGS_PUBLISHED_AT ON LISTINGS (PUBLISHED_AT);

-- Orders
CREATE INDEX IDX_ORDERS_BUYER_CREATED ON ORDERS (BUYER_ID, CREATED_AT);

CREATE INDEX IDX_ORDERS_SELLER_CREATED ON ORDERS (SELLER_ID, CREATED_AT);

CREATE INDEX IDX_ORDERS_STATUS_CREATED ON ORDERS (ORDER_STATUS_ID, CREATED_AT);

-- Order items
CREATE INDEX IDX_ORDER_ITEMS_ORDER ON ORDER_ITEMS (ORDER_ID);

-- Payments
CREATE INDEX IDX_PAYMENTS_ORDER ON PAYMENTS (ORDER_ID);

-- Listing history
CREATE INDEX IDX_LISTING_HISTORY_LISTING_DATE ON LISTING_STATUS_HISTORY (LISTING_ID, CHANGED_AT);

-- Order history
CREATE INDEX IDX_ORDER_HISTORY_ORDER_DATE ON ORDER_STATUS_HISTORY (ORDER_ID, CHANGED_AT);

-- Reviews
CREATE INDEX IDX_REVIEWS_REVIEWEE ON REVIEWS (REVIEWEE_ID);

